package com.khaled;

public class PrimeValue {
    

    private int number;
    private boolean prime;

    public void setNumber(int n)
    {
        number = n;
    }

    public void setPrime(boolean t)
    {
        prime = t;
    }

    public int getNumber()
    {
        return number;
    }

    public boolean getPrime()
    {
        return prime;
    }
    
}
